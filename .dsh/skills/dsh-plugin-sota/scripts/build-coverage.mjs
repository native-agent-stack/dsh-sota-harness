#!/usr/bin/env node
/**
 * Generate docs/plugin-landscape/coverage.md from data/stats.json.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DOCS = process.env.DSH_DOCS_DIR ? path.resolve(process.env.DSH_DOCS_DIR) : path.resolve(ROOT, '../../../docs/plugin-landscape')
const OUT = path.join(DOCS, 'coverage.md')

async function main() {
  const stats = JSON.parse(await fs.readFile(path.join(ROOT, 'data', 'stats.json'), 'utf8'))
  const fmt = (n) => Number(n).toLocaleString('en-US')
  const lines = []
  lines.push('# Catalog coverage report')
  lines.push('')
  lines.push('Generated: ' + stats.generatedAt)
  lines.push('')
  lines.push('## Sources')
  lines.push('')
  lines.push('- README: ' + stats.sources.readme)
  lines.push('- Plugin index: ' + stats.sources.index)
  lines.push('')
  lines.push('## Totals')
  lines.push('')
  lines.push('| Metric | Value |')
  lines.push('|---|---:|')
  lines.push('| Listed entries | ' + fmt(stats.totals.entries) + ' |')
  lines.push('| npm-indexed | ' + fmt(stats.totals.npmIndexed) + ' |')
  lines.push('| unique npm packages | ' + fmt(stats.totals.uniqueNpmNames) + ' |')
  lines.push('| GitHub-only | ' + fmt(stats.totals.githubOnly) + ' |')
  lines.push('| npm match rate | ' + stats.totals.npmMatchRate + '% |')
  lines.push('| Categories | ' + stats.totals.categories + ' |')
  lines.push('| Layers | ' + stats.totals.layers + ' |')
  lines.push('| Entries with an install command | ' + fmt(stats.totals.withInstallCommand) + ' |')
  lines.push('| Unique titles | ' + fmt(stats.totals.uniqueTitles) + ' |')
  lines.push('| Index-only plugins (outside the listed count) | ' + stats.coverage.indexOnly + ' |')
  lines.push('| Known universe (listed + index-only) | ' + fmt(stats.totals.entries + stats.coverage.indexOnly) + ' |')
  lines.push('')
  lines.push('## Category coverage')
  lines.push('')
  lines.push('| Key | Category | Entries | npm | GitHub-only | Primary layer |')
  lines.push('|---|---|---:|---:|---:|---|')
  for (const c of stats.categories) {
    lines.push('| ' + c.key + ' | ' + c.title + ' | ' + fmt(c.count) + ' | ' + fmt(c.npmCount) + ' | ' + fmt(c.count - c.npmCount) + ' | ' + c.layer + ' |')
  }
  lines.push('')
  lines.push('## Layer distribution')
  lines.push('')
  lines.push('| Layer | Name | Primary categories | Entries mentioning |')
  lines.push('|---|---|---:|---:|')
  for (const l of stats.layers) lines.push('| ' + l.id + ' | ' + l.name + ' | ' + fmt(l.primary) + ' | ' + fmt(l.mentions) + ' |')
  lines.push('')
  lines.push('L0 has no category of its own because it is a cross-cutting distribution layer. L9 owns the market/manager category. A mention count is not a quality count.')
  lines.push('')
  lines.push('## Signals')
  lines.push('')
  lines.push('Top curated terms:')
  lines.push('')
  for (const k of stats.keywords.slice(0, 20)) lines.push('- ' + k.term + ': ' + k.count)
  lines.push('')
  lines.push('Top heuristic tags:')
  lines.push('')
  for (const t of stats.tags.slice(0, 15)) lines.push('- ' + t.tag + ': ' + t.count)
  lines.push('')
  lines.push('## Match quality')
  lines.push('')
  lines.push('| Check | Value |')
  lines.push('|---|---:|')
  lines.push('| Index plugins | ' + fmt(stats.coverage.indexPlugins) + ' |')
  lines.push('| Matched README entries | ' + fmt(stats.coverage.matchedToNpmIndex) + ' |')
  lines.push('| Index-only entries | ' + stats.coverage.indexOnly + ' |')
  lines.push('| README entries | ' + fmt(stats.coverage.readmeEntries) + ' |')
  lines.push('| README entries skipped | ' + stats.coverage.readmeSkipped + ' |')
  lines.push('| Duplicate ids | ' + stats.coverage.duplicateIds + ' |')
  lines.push('')
  if (stats.coverage.indexOnly > 0) {
    lines.push('## Index-only plugins')
    lines.push('')
    lines.push('These are present in the npm index but absent from the awesome-list README. They are recorded outside the ' + Number(stats.totals.entries).toLocaleString('en-US') + ' listed-entry count.')
    lines.push('')
    for (const x of stats.coverage.indexOnlySample) {
      lines.push('- ' + x.title + ' (' + (x.name || 'no npm name') + ') — category ' + (x.categoryKey || 'unknown'))
    }
    lines.push('')
  }
  lines.push('## Limits')
  lines.push('')
  for (const c of stats.caveats) lines.push('- ' + c)
  lines.push('')
  lines.push('## Validate')
  lines.push('')
  lines.push('~~~sh')
  lines.push('cd .dsh/skills/dsh-plugin-sota')
  lines.push('node scripts/refresh-catalog.mjs --check')
  lines.push('node scripts/query.mjs stats')
  lines.push('~~~')
  lines.push('')
  await fs.writeFile(OUT, lines.join('\n'))
  console.log('Wrote ' + OUT)
}
main().catch((e) => { console.error('build-coverage: ' + e.message); process.exit(1) })
